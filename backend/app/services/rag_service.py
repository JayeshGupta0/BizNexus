class RAGService:
    def get_pipeline_architecture(self) -> List[Dict[str, Any]]:
        return RAG_ARCHITECTURE_STAGES

    def process_query(self, query: str) -> AIChatResponse:
        q = query.lower()
        if any(k in q for k in ["potential", "lead", "opportunity", "highest"]):
            ans = PRESET_ANSWERS["potential"]
        elif any(k in q for k in ["top-selling", "product", "best selling", "sales"]):
            ans = PRESET_ANSWERS["top-selling"]
        elif any(k in q for k in ["overdue", "invoice", "unpaid", "receivable"]):
            ans = PRESET_ANSWERS["overdue"]
        elif any(k in q for k in ["report", "pdf", "summarize", "document", "q2"]):
            ans = PRESET_ANSWERS["report"]
        else:
            ans = {
                "content": f"Based on your enterprise CRM and ERP records, I analyzed: '{query}'. Revenue is up 18.4% this month, with 1,248 active leads and ₹42.8L monthly revenue. All indexed documents in ChromaDB are query-ready.",
                "sources": ["CRM Database", "Financial Ledger"],
                "type": "insight",
                "follow_ups": ["Which leads have the highest potential value?", "What were our top-selling products?", "Which invoices are overdue?"]
            }
        return AIChatResponse(**ans)

rag_service = RAGService()
